#!/usr/bin/env python3
"""Rewrite A40_ACV_padring.v so iverilog can elaborate it.

The integrator's padframe generator names every pad-cell instance identically
to its slot net, e.g.

    gf180mcu_fd_io__bi_t N01 (.CS(N01_CS), ... .PAD(N01) ...);

with `inout N01;` also declared.  Yosys (P&R) tolerates the instance/net name
clash; iverilog rejects it ("'N01' has already been declared ... as a net").

This appends `_cell` to the *instance identifier only* -- every port
connection, including `.PAD(N01)`, is left untouched -- so the elaborated
netlist is functionally identical to what P&R consumes.  Regenerated at build
time from the committed A40_ACV_padring.v, so it cannot drift.

    mk_padring_sim.py <in A40_ACV_padring.v> <out A40_ACV_padring_sim.v>
"""
import re
import sys

src = sys.argv[1]
dst = sys.argv[2]

text = open(src).read()
# `<ws>gf180mcu_fd_io__<cell><ws><inst><ws>(`  where <inst> is a bare slot
# token (N01..W22) that collides with the inout port of the same name.
patched, n = re.subn(
    r"(gf180mcu_fd_io__[A-Za-z0-9_]+\s+)([NESW]\d{2})(\s*\()",
    r"\1\2_cell\3",
    text,
)
if n == 0:
    sys.exit("mk_padring_sim.py: no pad-cell instances matched -- has the "
             "generator output format changed?")

with open(dst, "w") as f:
    f.write("// GENERATED by cocotb/hdl/mk_padring_sim.py from A40_ACV_padring.v\n")
    f.write("// Pad-cell instance names get a _cell suffix so iverilog accepts\n")
    f.write("// the instance/net name clash; nothing else changes.\n")
    f.write(patched)
print(f"mk_padring_sim.py: renamed {n} pad-cell instances -> {dst}")
